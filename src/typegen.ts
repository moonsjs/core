import { mkdirSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { scanRoutes } from "./routes";
import type { RouteDefinition } from "./types";

export interface GenerateTypesArgs {
  /** Direktori route; relatif di-resolve terhadap cwd. */
  routesDir: string;
  /** Path file config, untuk import type di `context.d.ts`. */
  configPath: string;
  /** Direktori output (".moons"). */
  outDir: string;
}

/**
 * Tulis `.moons/routes.d.ts` dan `.moons/context.d.ts` (PRD §6.3, §13).
 * Catatan: file `routes.d.ts` diakhiri `export {}` agar `declare module`
 * berperilaku sebagai module augmentation (di luar snippet §13, wajib untuk TS).
 */
export async function generateTypes(args: GenerateTypesArgs): Promise<void> {
  const routes = scanRoutes(args.routesDir).filter((route) => route.kind === "page");

  mkdirSync(args.outDir, { recursive: true });
  writeFileSync(join(args.outDir, "routes.d.ts"), renderRoutesDts(routes), "utf8");
  writeFileSync(join(args.outDir, "context.d.ts"), renderContextDts(args), "utf8");
}

function renderRoutesDts(routes: RouteDefinition[]): string {
  const lines: string[] = [
    "// Generated by @moons (generateTypes). Do not edit manually.",
    'declare module "@moonsjs/react" {',
    "  export interface RouteMap {",
  ];

  for (const route of routes) {
    lines.push(`    "${routeMapKey(route)}": { params: ${paramsLiteral(route.params)} };`);
  }

  lines.push(
    "  }",
    "  export type RoutePath = keyof RouteMap;",
    '  export type RouteParams<P extends RoutePath> = RouteMap[P]["params"];',
    "}",
    "",
    "export {};",
    "",
  );

  return lines.join("\n");
}

function renderContextDts(args: GenerateTypesArgs): string {
  const configModule = relativeImport(args.outDir, args.configPath);
  return [
    "// Generated by @moons (generateTypes). Do not edit manually.",
    `import type config from "${configModule}";`,
    "",
    "export type Ctx = Awaited<ReturnType<typeof config.context>>;",
    "",
    "declare global {",
    "  type Ctx = Awaited<ReturnType<typeof config.context>>;",
    "}",
    "",
  ].join("\n");
}

/** "/users/:id" + params ["id"] → "/users/[id]"; "/docs/*" + ["rest"] → "/docs/[...rest]". */
export function routeMapKey(route: RouteDefinition): string {
  const queue = [...route.params];
  return route.path
    .split("/")
    .map((segment) => {
      if (segment === "*") {
        const name = queue.pop();
        return name === undefined ? "[...rest]" : `[...${name}]`;
      }
      if (segment.startsWith(":")) {
        const name = queue.shift();
        return name === undefined ? "[param]" : `[${name}]`;
      }
      return segment;
    })
    .join("/");
}

function paramsLiteral(params: string[]): string {
  if (params.length === 0) {
    return "{}";
  }
  return `{ ${params.map((param) => `${param}: string`).join("; ")} }`;
}

function relativeImport(outDir: string, configPath: string): string {
  let rel = relative(outDir, configPath);
  rel = sep === "/" ? rel : rel.split(sep).join("/");
  if (!rel.startsWith(".")) {
    rel = `./${rel}`;
  }
  return rel.replace(/\.tsx?$/, "");
}
